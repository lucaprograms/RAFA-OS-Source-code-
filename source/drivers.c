/* --- Reboot & Shutdown --- */

void reboot(void) {
    // ACPI reset
    outb(0xCF9, 0x02);
    outb(0xCF9, 0x06);

    // PS/2 reset (legacy)
    while (inb(0x64) & 0x02);
    outb(0x64, 0xFE);

    // Triple fault fallback
    __asm__ volatile ("lidt (0)");
    __asm__ volatile ("int $3");
}

void shutdown(void) {
    // ACPI S5 (common)
    outw(0x604, 0x2000);
    outw(0xB004, 0x2000);

    // QEMU-specific
    outb(0xF4, 0x00);
}

