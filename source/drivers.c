{
  return caps_lock;
}
void stop_speaker(void) {
    uint8_t speaker_state = inb(SPEAKER_PORT) & 0xFC;
    outb(SPEAKER_PORT, speaker_state);
}

void play_startup_chime(void) {
    // Divisors for a bright, classic ascending Major Arpeggio:
    // A4 (~440Hz), C#5 (~554Hz), E5 (~659Hz), A5 (~880Hz)
    uint16_t chime_notes[] = {2711, 2154, 1809, 1355};
    
    // Enable the PC speaker and route it to PIT Channel 2
    uint8_t speaker_on = inb(SPEAKER_PORT) | 3;
    outb(SPEAKER_PORT, speaker_on);

    // Play each note distinctly
    for (int i = 0; i < 4; i++) {
        set_pit_frequency(chime_notes[i]);
        
        // If your delay_ms_software is calibrated for actual milliseconds:
        // Use 120ms for the first 3 notes, and 400ms for the final chord resolution.
        if (i < 3) {
            delay_ms_software(120); 
        } else {
            delay_ms_software(400); // Hold the last high note longer
        }
    }

    // Shut off the speaker cleanly so it doesn't hum forever
    stop_speaker();
}
uint32_t IsVirtualMachine(void) {
    uint32_t EcxResult = 0;
    uint32_t Trash = 0;

    __asm__ volatile (
        "cpuid"
        : "=a"(Trash), "=b"(Trash), "=c"(EcxResult), "=d"(Trash)
        : "a"(1)
    );

    return (EcxResult >> 31) & 1;
}

