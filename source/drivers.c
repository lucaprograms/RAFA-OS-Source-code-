void init_fpu(void) {
    uint64_t cr4; // Changed from uint32_t to uint64_t for 64-bit compilation
    
    // Initialize FPU hardware
    __asm__ volatile ("finit");

    // Enable SSE and Floating Point Exceptions in CR4 register
    __asm__ volatile ("mov %%cr4, %0" : "=r"(cr4));
    cr4 |= (1 << 9) | (1 << 10); // Set OSFXSR and OSXMMEXCPT bits
    __asm__ volatile ("mov %0, %%cr4" :: "r"(cr4));
}
