/* --- Keyboard --- */

int shift_down = 0;
int caps_lock  = 0;

char get_hardware_keypress(void) {

    if ((inb(0x64) & 1) == 0)
        return 0;

    uint8_t sc = inb(0x60);

    /* Key release */
    if (sc & 0x80) {
        uint8_t code = sc & 0x7F;

        /* Shift released */
        if (code == 0x2A || code == 0x36)
            shift_down = 0;

        return 0;
    }

    /* Shift pressed */
    if (sc == 0x2A || sc == 0x36) {
        shift_down = 1;
        return 0;
    }

    /* Caps Lock */
    if (sc == 0x3A) {
        caps_lock = !caps_lock;
        return 0;
    }

    /* ESC → reboot */
    if (sc == 0x01) {
        reboot();
        return 0;
    }

    /* F1 → shutdown */
    if (sc == 0x3B) {
        shutdown();
        return 0;
    }

    char c = scancode_to_ascii[sc];

    /* Letters: Shift + Caps logic */
    if (c >= 'a' && c <= 'z') {
        int upper = caps_lock;
        if (shift_down)
            upper = !upper;
        if (upper)
            c -= 32;
        return c;
    }

    /* Shifted symbols (including '=' → '+') */
    if (shift_down) {
        char shifted = scancode_shift_ascii[sc];
        if (shifted != 0)
            return shifted;
    }

    return c;
}

